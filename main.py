def buffer_request(query, variables=None):
    response = requests.post(
        "https://api.buffer.com",
        headers={
            "Authorization": f"Bearer {BUFFER_KEY}",
            "Content-Type": "application/json",
        },
        json={
            "query": query,
            "variables": variables or {},
        },
        timeout=60,
    )

    response.raise_for_status()

    result = response.json()

    if result.get("errors"):
        raise RuntimeError(
            "Buffer API error:\n"
            + str(result["errors"])
        )

    return result["data"]


def get_linkedin_channel():
    # Get Buffer organization.
    data = buffer_request(
        """
        query GetOrganizations {
          account {
            organizations {
              id
              name
            }
          }
        }
        """
    )

    organizations = data["account"]["organizations"]

    if not organizations:
        raise RuntimeError("No Buffer organization found.")

    organization_id = organizations[0]["id"]

    print(f"Buffer organization: {organizations[0]['name']}")

    # Get connected social accounts.
    data = buffer_request(
        """
        query GetChannels($organizationId: OrganizationId!) {
          channels(input: { organizationId: $organizationId }) {
            id
            name
            service
          }
        }
        """,
        {
            "organizationId": organization_id
        },
    )

    channels = data["channels"]

    print("Connected Buffer channels:")
    for channel in channels:
        print(
            f"- {channel['name']} / "
            f"{channel['service']} / "
            f"{channel['id']}"
        )

    linkedin_channels = [
        channel
        for channel in channels
        if str(channel["service"]).lower() == "linkedin"
    ]

    if not linkedin_channels:
        raise RuntimeError(
            "LinkedIn is not connected to Buffer."
        )

    linkedin = linkedin_channels[0]

    print(f"Using LinkedIn: {linkedin['name']}")

    return linkedin["id"]


def create_buffer_draft(channel_id, post):
    mutation = """
    mutation CreateDraftPost($input: CreatePostInput!) {
      createPost(input: $input) {
        ... on PostActionSuccess {
          post {
            id
            text
          }
        }

        ... on MutationError {
          message
        }
      }
    }
    """

    data = buffer_request(
        mutation,
        {
            "input": {
                "text": post,
                "channelId": channel_id,
                "schedulingType": "automatic",
                "mode": "addToQueue",
                "saveToDraft": True,
                "aiAssisted": True,
            }
        },
    )

    result = data["createPost"]

    if result.get("message"):
        raise RuntimeError(
            "Buffer could not create draft: "
            + result["message"]
        )

    print("\nSUCCESS!")
    print("Draft created in Buffer.")
    print(result)


# -------------------------
