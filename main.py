# -------------------------
# GEMINI
# -------------------------

def generate_post():
    # If one model is temporarily unavailable, try another free Flash model.
    models = [
        "gemini-3.8-flash",
        "gemini-3.7-flash",
        "gemini-3.6-flash",
        "gemini-3.5-flash",
    ]

    url = "https://generativelanguage.googleapis.com/v1beta/interactions"

    for model in models:
        for attempt in range(3):
            print(f"Trying Gemini: {model}, attempt {attempt + 1}")

            response = requests.post(
                url,
                headers={
                    "x-goog-api-key": GEMINI_KEY,
                    "Content-Type": "application/json",
                },
                json={
                    "model": model,
                    "input": PROMPT,
                    "generation_config": {
                        "temperature": 1.0
                    }
                },
                timeout=120,
            )

            # Temporary Google error — retry.
            if response.status_code in [429, 500, 502, 503, 504]:
                print(
                    f"Gemini temporarily unavailable: "
                    f"{response.status_code} {response.text[:300]}"
                )
                time.sleep(5 * (attempt + 1))
                continue

            # Authentication problem.
            if response.status_code in [401, 403]:
                raise RuntimeError(
                    "Gemini API key was rejected. "
                    "Create a new API key in Google AI Studio and replace "
                    "GEMINI_API_KEY in GitHub Secrets.\n\n"
                    + response.text
                )

            response.raise_for_status()
            data = response.json()

            # Find the final text generated by Gemini.
            texts = []

            for step in data.get("steps", []):
                if step.get("type") == "model_output":
                    for content in step.get("content", []):
                        if (
                            content.get("type") == "text"
                            and content.get("text")
                        ):
                            texts.append(content["text"])

            if texts:
                post = "\n".join(texts).strip()
                print("\nPOST GENERATED:\n")
                print(post)
                return post

            print("Gemini returned no text:")
            print(data)

    raise RuntimeError("All Gemini models failed after retries.")


